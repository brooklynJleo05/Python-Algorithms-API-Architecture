from pgmpy.models import DiscreteBayesianNetwork # Probabilistic Graphical Models
from pgmpy.factors.discrete import TabularCPD
from pgmpy.inference import VariableElimination

# Step 1: Define the structure of the Bayesian Network
# Cloudy -> Rain -> Umbrella
model = DiscreteBayesianNetwork([('Cloudy', 'Rain'), ('Rain', 'Umbrella')])

# Step 2: Define the Conditional Probability Distributions (CPDs)
# P(Cloudy) - Prior probability of being cloudy
cpd_cloudy = TabularCPD(variable='Cloudy', variable_card=2, values=[[0.5], [0.5]])  # 50% chance of being cloudy

# P(Rain | Cloudy) - Probability of rain given whether it's cloudy
cpd_rain = TabularCPD(
    variable='Rain',
    variable_card=2,
    values=[
        [0.8, 0.2],  # P(Rain=False | Cloudy=False)=0.8, P(Rain=False | Cloudy=True)=0.2
        [0.2, 0.8],  # P(Rain=True | Cloudy=False)=0.2, P(Rain=True | Cloudy=True)=0.8
    ],
    evidence=['Cloudy'],
    evidence_card=[2],
)

# P(Umbrella | Rain) - Probability of carrying an umbrella given whether it's raining
cpd_umbrella = TabularCPD(
    variable='Umbrella',
    variable_card=2,
    values=[
        [0.9, 0.3],  # P(Umbrella=False | Rain=False)=0.9, P(Umbrella=False | Rain=True)=0.3
        [0.1, 0.7],  # P(Umbrella=True | Rain=False)=0.1, P(Umbrella=True | Rain=True)=0.7
    ],
    evidence=['Rain'],
    evidence_card=[2],
)

# Step 3: Add the CPDs to the model
model.add_cpds(cpd_cloudy, cpd_rain, cpd_umbrella)

# Verify that the model is correct
assert model.check_model()

# Step 4: Perform inference
# Use Variable Elimination for inference
inference = VariableElimination(model)

# Example 1: What is the probability that it's raining given someone is carrying an umbrella?
result = inference.query(variables=['Rain'], evidence={'Umbrella': 1})
print("\nP(Rain | Umbrella=True):")
print(result)

# Example 2: What is the probability that it is cloudy given someone is carrying an umbrella?
result = inference.query(variables=['Cloudy'], evidence={'Umbrella': 1})
print("\nP(Cloudy | Umbrella=True):")
print(result)

# Example 3: What is the probability of rain with no additional evidence (prior probability)?
result = inference.query(variables=['Rain'])
print("\nP(Rain):")
print(result)


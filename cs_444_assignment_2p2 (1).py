from queue import PriorityQueue

# A* Search Algorithm for Grid
def a_star_search(grid, start, goal):
    # Heuristic function: Manhattan distance
    def heuristic(a, b):
        return abs(a[0] - b[0]) + abs(a[1] - b[1])

    # Priority queue to store the nodes to be explored
    open_list = PriorityQueue()
    open_list.put((0, start))

    # Dictionary to store the cost to reach each node
    g_costs = {start: 0}

    # Dictionary to store the path
    came_from = {start: None}

    # Directions for moving (up, down, left, right)
    directions = [(-1, 0), (1, 0), (0, -1), (0, 1)]

    while not open_list.empty():
        # Get the node with the lowest estimated cost (f = g + h)
        current_cost, current = open_list.get()

        # If we have reached the goal, reconstruct the path
        if current == goal:
            path = []
            while current:
                path.append(current)
                current = came_from[current]
            return path[::-1] # Return reversed path from start to goal

        # Explore neighbors (up, down, left, right)
        for direction in directions:
            neighbor = (current[0] + direction[0], current[1] + direction[1])

            # Ensure the neighbor is within grid bounds
            if 0 <= neighbor[0] < len(grid) and 0 <= neighbor[1] < len(grid[0]):
                # Ensure the neighbor is not a blocked cell (obstacle)
                if grid[neighbor[0]][neighbor[1]] != 1:
                    # Calculate the tentative g_cost (current path cost + movement cost)
                    tentative_g_cost = g_costs[current] + grid[neighbor[0]][neighbor[1]]

                    # If this path to neighbor is better or neighbor has not been visited
                    if neighbor not in g_costs or tentative_g_cost < g_costs[neighbor]:
                        g_costs[neighbor] = tentative_g_cost
                        f_cost = tentative_g_cost + heuristic(neighbor, goal) # f(n) = g(n) + h(n)
                        open_list.put((f_cost, neighbor))
                        came_from[neighbor] = current

    return None
    # No path found

# Define the grid (0: open with cost 1, n: open with cost n, 1: blocked)
grid = [
    [0, 1, 0, 0, 0],
    [0, 1, 0, 1, 0],
    [0, 2, 0, 1, 0],
    [1, 1, 0, 1, 0],
    [0, 0, 0, 0, 0]
]

# Start and goal positions
start = (0, 0) # Starting point (top-left corner)
goal = (4, 4)
# Goal point (bottom-right corner)

# Run A* Search
path = a_star_search(grid, start, goal)

if path:
    print("Path from {} to {}: {}".format(start, goal, path))
else:
    print("No path found.")



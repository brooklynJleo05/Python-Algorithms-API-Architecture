# Part 1: Python Functions
def calculates(n1, n2, n3):
    total = n1 + n2 + n3
    avg = total / 3
    max_val = max(n1, n2, n3)
    min_val = min(n1, n2, n3)
    return {
        "sum": total,
        "average": avg,
        "maximum": max_val,
        "minimum": min_val
    }

# dequeue: double ended queue. A queue allows yout to add
# or remove elements from both ends.
# append(), appendleft(), pop(), popleft()
def bfs(graph, start):
    visited = set() # keep track of visited nodes
    queue = deque([start]) # initialize a queue with the start node
    bfs_path = []

    while queue: # |       A|  --> node = A
        node = queue.popleft() #  |        | --> node = A
        if node not in visited:
            bfs_path.append(node) # process the node
            visited.add(node)

            if node in graph:
                for neighbor in graph[node]:      # Neighbors of A: B, C
                    if neighbor not in visited:
                        queue.append(neighbor)

    return bfs_path

